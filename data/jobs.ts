export function generateMoreJobs(startIndex: number, count: number = 15): Job[] {
  const currentTimestamp = Date.now();
  const minuteMs = 60 * 1000;

  return Array.from({ length: count }, (_, i) => {
    const jobIndex = startIndex + i + 1;
    const template = jobTemplates[(jobIndex - 1) % jobTemplates.length];
    const minutesAgo = (jobIndex * 7) % 1440;

    return {
      id: `job-${jobIndex}`,
      title: `${template.title} #${jobIndex}`,
      company: template.company,
      savedDate: '18 Nov',
      savedTime: '11:00 AM',
      savedTimestamp: currentTimestamp - minutesAgo * minuteMs,
      magicVerdict: template.magicVerdict,
      verdictScore: template.verdictScore,
      modelScores: template.modelScores,
      isCream: template.isCream,
      creamCount: template.creamCount,
      technology: template.technology,
      budgetType: template.budgetType,
      budgetAmount: template.budgetAmount,
      budgetNumeric: template.budgetNumeric,
      posted:
        minutesAgo < 60
          ? `${minutesAgo} minutes ago`
          : `${Math.floor(minutesAgo / 60)} hours ago`,
      postedMinutesAgo: minutesAgo,
      totalSpent: template.totalSpent,
      totalSpentNumeric: template.totalSpentNumeric,
      location: template.location,
      status: 'Not Applied',
      url: `https://www.upwork.com/jobs/~${jobIndex}loadmore`,
    };
  });
}
